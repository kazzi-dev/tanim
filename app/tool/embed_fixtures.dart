// Packs test/fixtures into integration_test/fixtures.g.dart so the model test
// can run on a phone, which can't read files from the laptop.
//
//   dart run tool/embed_fixtures.dart
import 'dart:convert';
import 'dart:io';

void main() {
  final dir = Directory('test/fixtures');
  final expected = File('${dir.path}/expected.json').readAsStringSync();
  final images = (jsonDecode(expected) as Map<String, dynamic>)['images'] as List;

  final out = StringBuffer()
    ..writeln('// GENERATED by tool/embed_fixtures.dart from test/fixtures. Do not edit.')
    ..writeln()
    ..writeln("const fixtureExpectedJson = r'''$expected''';")
    ..writeln()
    ..writeln('const fixturePhotosBase64 = <String, String>{');
  for (final image in images.cast<Map<String, dynamic>>()) {
    final name = image['file'] as String;
    out.writeln("  '$name': '${base64Encode(File('${dir.path}/$name').readAsBytesSync())}',");
  }
  out.writeln('};');

  File('integration_test/fixtures.g.dart').writeAsStringSync(out.toString());
  stdout.writeln('Embedded ${images.length} photos into integration_test/fixtures.g.dart');
}
